inline readstat_measure_e measureType(SEXP x) {
  if (Rf_inherits(x, "ordered")) {
    return READSTAT_MEASURE_ORDINAL;
  } else if (Rf_inherits(x, "factor")) {
    return READSTAT_MEASURE_NOMINAL;
  } else {
    switch (TYPEOF(x)) {
    case INTSXP:
    case REALSXP:
      return READSTAT_MEASURE_SCALE;
    case LGLSXP:
    case STRSXP:
      return READSTAT_MEASURE_NOMINAL;
    default:
      return READSTAT_MEASURE_UNKNOWN;
    }
  }
}

inline bool has_labels(cpp11::sexp x) {
  return Rf_inherits(x, "haven_labelled") && TYPEOF(x.attr("labels")) != NILSXP;
}

// Variable metadata -----------------------------------------------------------
// Generated by writer_meta() in R

inline SEXP list_get(SEXP x, const char* name) {
  SEXP names = Rf_getAttrib(x, R_NamesSymbol);
  for (int i = 0; i < Rf_length(x); ++i) {
    if (strcmp(CHAR(STRING_ELT(names, i)), name) == 0) {
      return VECTOR_ELT(x, i);
    }
  }
  return R_NilValue;
}

inline const char* list_string(SEXP x, const char* name) {
  SEXP val = list_get(x, name);
  return TYPEOF(val) == STRSXP && Rf_length(val) == 1 ? string_utf8(val, 0)
                                                      : NULL;
}

inline int list_int(SEXP x, const char* name) {
  SEXP val = list_get(x, name);
  switch (TYPEOF(val)) {
  case INTSXP:
    return INTEGER(val)[0];
  case REALSXP:
    return REAL(val)[0];
  }
  return 0;
}

struct VarMeta {
  const char* format;
  const char* informat;
  int width;
  int display_width;
  readstat_measure_t measure;
  readstat_alignment_t alignment;
  const char* type;

  VarMeta(SEXP x) {
    format = list_string(x, "format");
    informat = list_string(x, "informat");
    width = list_int(x, "width");
    display_width = list_int(x, "display_width");
    type = list_string(x, "type");

    measure = READSTAT_MEASURE_UNKNOWN;
    const char* measure_s = list_string(x, "measure");
    if (measure_s != NULL) {
      if (strcmp(measure_s, "nominal") == 0)
        measure = READSTAT_MEASURE_NOMINAL;
      else if (strcmp(measure_s, "ordinal") == 0)
        measure = READSTAT_MEASURE_ORDINAL;
      else if (strcmp(measure_s, "scale") == 0)
        measure = READSTAT_MEASURE_SCALE;
    }

    alignment = READSTAT_ALIGNMENT_UNKNOWN;
    const char* alignment_s = list_string(x, "alignment");
    if (alignment_s != NULL) {
      if (strcmp(alignment_s, "left") == 0)
        alignment = READSTAT_ALIGNMENT_LEFT;
      else if (strcmp(alignment_s, "center") == 0)
        alignment = READSTAT_ALIGNMENT_CENTER;
      else if (strcmp(alignment_s, "right") == 0)
        alignment = READSTAT_ALIGNMENT_RIGHT;
    }
  }

  bool has_type(const char* x) const {
    return type != NULL && strcmp(type, x) == 0;
  }
};

// Defines variables (and their label sets and missing values) in a
// readstat writer, choosing storage types and formats appropriate for
// the file format.
class VariableDefiner {
  FileExt ext_;
  FileVendor vendor_;
  int version_;
  int strl_threshold_;
  std::unordered_map<std::string, readstat_string_ref_t*>* string_ref_;
  readstat_writer_t* writer_;

public:
  VariableDefiner(
      readstat_writer_t* writer,
      FileExt ext,
      std::unordered_map<std::string, readstat_string_ref_t*>* string_ref)
      : ext_(ext),
        vendor_(extVendor(ext)),
        version_(0),
        strl_threshold_(0),
        string_ref_(string_ref),
        writer_(writer) {}

  void setVersion(int version) { version_ = version; }

  void setStrLThreshold(int strl_threshold) {
    strl_threshold_ = strl_threshold;
  }

  // `x` must be an integer, double, or character vector
  readstat_error_t
  defineVariable(cpp11::sexp x, VarType type, const char* name, SEXP meta_sxp) {
    VarMeta meta(meta_sxp);
    readstat_label_set_t* labelSet;
    readstat_variable_t* var;

    switch (TYPEOF(x)) {
    case INTSXP:
      labelSet = label_set(cpp11::integers(x), name);
      var = readstat_add_variable(
          writer_,
          name,
          stataNumericType(x, type, meta, READSTAT_TYPE_INT32),
          meta.width);
      break;
    case REALSXP:
      labelSet = label_set(cpp11::doubles(x), name);
      var = readstat_add_variable(
          writer_,
          name,
          stataNumericType(x, type, meta, READSTAT_TYPE_DOUBLE),
          meta.width);
      break;
    case STRSXP:
      labelSet = label_set(cpp11::strings(x), name);
      var = addStringVariable(cpp11::strings(x), name, labelSet, meta);
      break;
    default:
      cpp11::stop(
          "Columns of type %s not supported yet", Rf_type2char(TYPEOF(x)));
    }

    setMetadata(var, x, type, meta, labelSet);
    addSpssMissing(var, x);
    return readstat_validate_variable(writer_, var);
  }

private:
  readstat_variable_t* addStringVariable(
      cpp11::strings x,
      const char* name,
      readstat_label_set_t* labelSet,
      const VarMeta& meta) {
    int width = stringWidth(x, name, labelSet, meta);

    // Use strL for "long" strings in stata. strL has an 80 byte overhead so
    // we use it when it's likely to be more efficient. The main downside of
    // strL is that it can't be used as a join key but this seems unlikely for
    // very long strings.
    bool strl = meta.has_type("strL") || width > strl_threshold_;
    if (ext_ != HAVEN_DTA || version_ < 117 || !strl) {
      return readstat_add_variable(writer_, name, READSTAT_TYPE_STRING, width);
    }

    for (int i = 0; i < x.size(); ++i) {
      // Stata has no missing strL; use an empty string instead
      std::string val(string_is_missing(x, i) ? "" : string_utf8(x, i));
      if (!string_ref_->count(val)) {
        (*string_ref_)[val] = readstat_add_string_ref(writer_, val.c_str());
      }
    }
    return readstat_add_variable(
        writer_, name, READSTAT_TYPE_STRING_REF, width);
  }

  // Label sets ---------------------------------------------------------------

  readstat_label_set_t* label_set(cpp11::integers x, const char* name) {
    if (Rf_inherits(x, "factor")) {
      readstat_label_set_t* labelSet =
          readstat_add_label_set(writer_, READSTAT_TYPE_INT32, name);

      cpp11::strings levels(x.attr("levels"));
      for (int i = 0; i < levels.size(); ++i)
        readstat_label_int32_value(labelSet, i + 1, string_utf8(levels, i));
      return labelSet;
    } else if (has_labels(x)) {
      readstat_label_set_t* labelSet =
          readstat_add_label_set(writer_, READSTAT_TYPE_INT32, name);

      cpp11::integers values(x.attr("labels"));
      cpp11::strings labels(values.attr("names"));

      for (int i = 0; i < values.size(); ++i)
        readstat_label_int32_value(labelSet, values[i], string_utf8(labels, i));
      return labelSet;
    }
    return NULL;
  }

  readstat_label_set_t* label_set(cpp11::doubles x, const char* name) {
    if (!has_labels(x))
      return NULL;

    readstat_label_set_t* labelSet =
        readstat_add_label_set(writer_, READSTAT_TYPE_DOUBLE, name);

    cpp11::doubles values(x.attr("labels"));
    cpp11::strings labels(values.attr("names"));

    for (int i = 0; i < values.size(); ++i) {
      char tag = tagged_na_value(values[i]);
      if (!std::isnan(values[i]) || tag == '\0') {
        readstat_label_double_value(
            labelSet, values[i], string_utf8(labels, i));
      } else {
        readstat_label_tagged_value(
            labelSet, write_tag(tag, vendor_), string_utf8(labels, i));
      }
    }
    return labelSet;
  }

  readstat_label_set_t* label_set(cpp11::strings x, const char* name) {
    if (!has_labels(x))
      return NULL;

    readstat_label_set_t* labelSet =
        readstat_add_label_set(writer_, READSTAT_TYPE_STRING, name);

    cpp11::strings values(x.attr("labels"));
    cpp11::strings labels(values.attr("names"));

    for (int i = 0; i < values.size(); ++i)
      readstat_label_string_value(
          labelSet, string_utf8(values, i), string_utf8(labels, i));
    return labelSet;
  }

  // Variable metadata
  // ----------------------------------------------------------

  void setMetadata(
      readstat_variable_t* var,
      cpp11::sexp x,
      VarType type,
      const VarMeta& meta,
      readstat_label_set_t* labelSet) {
    readstat_variable_set_format(var, var_format(meta, type));
    if (meta.informat != NULL)
      readstat_variable_set_informat(var, meta.informat);
    readstat_variable_set_label(var, var_label(x));
    readstat_variable_set_label_set(var, labelSet);
    readstat_variable_set_measure(
        var,
        meta.measure == READSTAT_MEASURE_UNKNOWN ? measureType(x)
                                                 : meta.measure);
    readstat_variable_set_display_width(var, meta.display_width);
    if (meta.alignment != READSTAT_ALIGNMENT_UNKNOWN)
      readstat_variable_set_alignment(var, meta.alignment);
  }

  const char* var_label(cpp11::sexp x) {
    cpp11::sexp label(x.attr("label"));

    if (label == R_NilValue)
      return NULL;

    return string_utf8(label, 0);
  }

  const char* var_format(const VarMeta& meta, VarType type) {
    if (meta.format != NULL)
      return meta.format;

    return defaultFormat(vendor_, type);
  }

  // Storage types and widths
  // ---------------------------------------------------

  // Stata storage types are fixed width, so like Stata's `compress`, use the
  // smallest integer type that can exactly represent every value.
  readstat_type_t stataNumericType(
      cpp11::sexp col,
      VarType type,
      const VarMeta& meta,
      readstat_type_t default_type) {
    if (ext_ != HAVEN_DTA)
      return default_type;
    // Datetimes are stored in milliseconds so need the precision of a double
    if (type == HAVEN_DATETIME)
      return READSTAT_TYPE_DOUBLE;

    // Use the Stata storage type from the metadata, if the values fit
    readstat_type_t meta_type = READSTAT_TYPE_DOUBLE;
    bool has_meta_type = true;
    if (meta.has_type("byte"))
      meta_type = READSTAT_TYPE_INT8;
    else if (meta.has_type("int"))
      meta_type = READSTAT_TYPE_INT16;
    else if (meta.has_type("long"))
      meta_type = READSTAT_TYPE_INT32;
    else if (meta.has_type("float"))
      meta_type = READSTAT_TYPE_FLOAT;
    else if (meta.has_type("double"))
      meta_type = READSTAT_TYPE_DOUBLE;
    else
      has_meta_type = false;

    if (has_meta_type && Rf_length(col) == 0)
      return meta_type;

    // Compute the range of non-missing values to find the smallest integer
    // type that can hold them; a fractional value forces double
    double min = R_PosInf, max = R_NegInf;
    int n = Rf_length(col);
    for (int i = 0; i < n; ++i) {
      double val;
      switch (TYPEOF(col)) {
      case INTSXP:
        if (INTEGER(col)[i] == NA_INTEGER)
          continue;
        val = INTEGER(col)[i];
        break;
      default:
        val = REAL(col)[i];
        if (!R_finite(val))
          continue;
        break;
      }

      if (val != std::trunc(val)) {
        if (has_meta_type && meta_type == READSTAT_TYPE_FLOAT &&
            (double)(float)val == val)
          continue;
        return READSTAT_TYPE_DOUBLE;
      }
      min = std::min(min, val);
      max = std::max(max, val);
    }
    // Remaining adjustments are integer shifts, so only affect the range
    min = adjustDatetimeFromR(vendor_, type, min);
    max = adjustDatetimeFromR(vendor_, type, max);

    // Honor the metadata type if every value fits in it
    if (has_meta_type) {
      bool fits = true;
      switch (meta_type) {
      case READSTAT_TYPE_INT8:
        fits = min >= -127 && max <= 100;
        break;
      case READSTAT_TYPE_INT16:
        fits = min >= -32767 && max <= 32740;
        break;
      case READSTAT_TYPE_INT32:
        fits = min >= -2147483647 && max <= 2147483620;
        break;
      default:
        break;
      }
      if (fits)
        return meta_type;
    }

    // Stata reserves the largest values of each type for missing values
    if (min >= -127 && max <= 100) {
      return READSTAT_TYPE_INT8;
    } else if (min >= -32767 && max <= 32740) {
      return READSTAT_TYPE_INT16;
    } else if (min >= -2147483647 && max <= 2147483620) {
      return READSTAT_TYPE_INT32;
    } else {
      return READSTAT_TYPE_DOUBLE;
    }
  }

  int stringWidth(
      cpp11::strings x,
      const char* name,
      readstat_label_set_t* labelSet,
      const VarMeta& meta) {
    int user_width = meta.width;
    int max_length = 1;
    for (int i = 0; i < x.size(); ++i) {
      int length = string_len_missing(x, i);
      if (length > max_length)
        max_length = length;
    }
    if (labelSet) {
      for (int i = 0; i < labelSet->value_labels_count; ++i) {
        int length = labelSet->value_labels[i].string_key_len;
        if (length > max_length)
          max_length = length;
      }
    }
    if (max_length > user_width) {
      if (user_width > 0) {
        cpp11::warning(
            "Column `%s` contains string values longer than user "
            "width %d. Width set to %d to accommodate.",
            name,
            user_width,
            max_length);
      }
      user_width = max_length;
    }
    return user_width;
  }

  // SPSS missing values
  // ---------------------------------------------------------

  void addSpssMissing(readstat_variable_t* var, cpp11::sexp x) {
    if (!Rf_inherits(x, "haven_labelled_spss"))
      return;

    SEXP na_range = x.attr("na_range");
    if (Rf_length(na_range) == 2) {
      if (TYPEOF(na_range) == REALSXP) {
        readstat_variable_add_missing_double_range(
            var, REAL(na_range)[0], REAL(na_range)[1]);
      } else if (TYPEOF(na_range) == INTSXP) {
        readstat_variable_add_missing_double_range(
            var, INTEGER(na_range)[0], INTEGER(na_range)[1]);
      } else if (TYPEOF(na_range) == STRSXP) {
        readstat_variable_add_missing_string_range(
            var,
            R_CHAR(STRING_ELT(na_range, 0)),
            R_CHAR(STRING_ELT(na_range, 1)));
      }
    }

    SEXP na_values = x.attr("na_values");
    int n = Rf_length(na_values);
    for (int i = 0; i < n; ++i) {
      if (TYPEOF(na_values) == REALSXP) {
        readstat_variable_add_missing_double_value(var, REAL(na_values)[i]);
      } else if (TYPEOF(na_values) == INTSXP) {
        readstat_variable_add_missing_double_value(var, INTEGER(na_values)[i]);
      } else if (TYPEOF(na_values) == STRSXP) {
        readstat_variable_add_missing_string_value(
            var, R_CHAR(STRING_ELT(na_values, i)));
      }
    }
  }
};

